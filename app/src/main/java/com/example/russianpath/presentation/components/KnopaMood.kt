package com.example.russianpath.presentation.components

/**
 * Настроение маскота Кнопы.
 *
 * Кнопа — анимированный персонаж-помощник, который сопровождает пользователя
 * на протяжении всего обучения. Его настроение меняется в зависимости от контекста.
 *
 * Используется в KnopaImage для выбора подходящего изображения/анимации.
 *
 * Переходы между настроениями:
 * ```
 * IDLE ←→ HAPPY ←→ EXCITED
 *   ↑        ↑
 *   ↓        ↓
 *  SAD    SURPRISED
 * ```
 */
enum class KnopaMood {
    /**
     * Нейтральное состояние.
     * Используется по умолчанию, когда нет особых событий.
     */
    IDLE,

    /**
     * Радостное состояние.
     * Используется при:
     * - Активном стрике (>0 дней)
     * - Хорошем результате урока (2 звезды)
     * - Повышении уровня
     */
    HAPPY,

    /**
     * Восторженное состояние.
     * Используется при:
     * - Идеальном результате (3 звезды, 100%)
     * - Длинном стрике (7+ дней)
     * - Получении достижения
     */
    EXCITED,

    /**
     * Грустное состояние.
     * Используется при:
     * - Плохом результате (0-1 звезда)
     * - Потере всех жизней
     * - Разрыве стрика
     */
    SAD,

    /**
     * Удивлённое состояние.
     * Используется при:
     * - Первом достижении
     * - Неожиданном бонусе
     * - Нахождении секретной темы
     */
    SURPRISED
}
